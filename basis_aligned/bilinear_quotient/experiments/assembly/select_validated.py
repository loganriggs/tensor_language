    pc=val<=3.20
    out={'kept':kept,'window_C':round(cost_c,4),
         'fr_sel':round(cost_s,4),'fr_val':round(val,4),
         'fr_val_deploy':round(valD,4),
         'pred_a':bool(pa),'pred_b':bool(pb),'pred_c':bool(pc)}
    print(f"(a) keeps exactly a5,a14,a16 (got {kept}): "
          f"{'HELD' if pa else 'FAILED'}")
    print(f"(b) FR-val within +-0.10 of FR-sel: "
          f"{'HELD' if pb else 'FAILED'}")
    print(f"(c) FR-val <= +3.20: {'HELD' if pc else 'FAILED'}")
    out['runtime_s']=time.time()-t0
    json.dump(out,open(OUT,'w'),indent=1)
    print(f'wrote {OUT} ({out["runtime_s"]:.0f}s)')

