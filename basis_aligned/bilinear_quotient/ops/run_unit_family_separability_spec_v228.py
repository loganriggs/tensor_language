EVAL = ("degree_synthetic_periphrastic_comparative", "degree_synthetic_periphrastic_superlative", "countability_few_little", "possessive_number_its_their", "polarity_any_some", "relative_animacy_whom_which", "comparative_complement_superior", "comparative_complement_inferior", "degree_much_very", "article_countability", "reflexive_number", "pronoun_number", "demonstrative_number", "reciprocal", "possessive_number", "quantifier_number", "object_pronoun_number", "polarity_state", "polarity_licensing", "polarity_addition", "dative_animacy_to_the", "wh_argument_who_what", )
COUNTED = ("comparative_complement_superior", "comparative_complement_inferior", "degree_much_very", "article_countability", "reflexive_number", "pronoun_number", "demonstrative_number", "reciprocal", "possessive_number", "quantifier_number", "object_pronoun_number", "polarity_state", "polarity_licensing", "polarity_addition", "dative_animacy_to_the", "wh_argument_who_what", )
