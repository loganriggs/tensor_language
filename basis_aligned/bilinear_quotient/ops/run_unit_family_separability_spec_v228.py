"""v228: within-family separability for v231's seven four-row passes (six with families; modal_ellipsis_can_must is a family-less
singleton and counts directly) and the re-check of EVERY counted member of the five families that grew (v212/v216/v220/v222 rule,
standing until board proposal (v) is answered).

v231 put the fifteenth eight spec-authored behaviours -- all grammatical cues with NEW readout tokens, after two inference zeros -- through
the four-row battery: 7/8 four-row, preds 6/6, and every pass has a constrained rank-1 extraction >= 0.99 (no hollow pass; v227's
when_where lesson). Families here (members = every screened behaviour with receipt units; controls included):
  degree = the six v224 members (best, largest, superior, inferior, much_very, so_such) + degree_synthetic_periphrastic_comparative
    (taller/more; 20 units, A1 ceiling 1.28 -- the strongest new set of the day) + degree_synthetic_periphrastic_superlative (tallest/most;
    26 units). Placed INSIDE degree, not in a family of their own, because `more`/`most` ARE degree markers and the v222 fusion
    (best/superior) was the degree-marker axis: the strict placement. Counted re-checks: superior, inferior, much_very.
  countability = countability (many/much), less_fewer_countability, article_countability (counted v220) + countability_few_little
    (few/little; 9 units, the weakest pass: dim 0.165, A1 ceiling 0.19, cdas 0.997) + countability_number_amount (rows 2+4 miss; control).
  number_readout = the v206/v208 union (reflexive, pronoun, demonstrative, reciprocal, possessive, quantifier, possessive_verbfinal,
    object_pronoun) + possessive_number_its_their (its/their; 7 units, first inanimate possessive). Counted re-checks: seven.
  polarity = the five v224 members + polarity_any_some (any/some; 15 units on the polarity hub 07:08/09:07/08:01). Counted re-checks:
    state, licensing, addition.
  animacy_wh = the five v226 members + relative_animacy_whom_which (whom/which; 19 units). Counted re-checks: dative_animacy, who_what.
Recipe as v198/.../v226: per evaluated member, arm `own` (own C_fit control) and arm `fam` (own C_fit + EVERY sibling's A1 FIT prep,
control_weight 30 x len(controls)); evaluated on the member's held A1 (extraction), each sibling's held A1 (|CE| leak) and held C.
Units frozen from the parent receipts (v231 for the new members).
    separable(member) := fam-arm sibling max|CE| <= 0.05 AND fam-arm own extraction >= 0.80 x own-arm own extraction
                         AND own-arm extraction >= 0.50 (v206 floor).
All members are prepared; EVAL = 6 new members + 16 counted re-checks (22 fits x 2 arms, ~70 s each: ~25 min -- the largest
separability rung so far, the price of the v222 re-check rule on the seven-member number family).
Count rule: each separable new EVAL member is a distinct circuit; a pair that leaks one way counts once (v216 aux-copy precedent); a
re-checked counted member that fails is RETRACTED (-1 each; v222 superlative_best precedent); modal_ellipsis_can_must counts on v231
alone (verb_preposition precedent). 53 -> up to 60.

REGISTERED BEFORE THE RUN (each coded predicate is the sentence here; bars in BARS):
    pred_a_new_separable   at least 3 of the 6 new members are separable (k_new). Expected fusion risk: comparative/superlative with
                           each other (both read tall/careful; the v222 best/superior precedent) and few_little with the fused
                           countability trio.                                                                            prior 60%
    pred_b_counted_kept    at least 13 of the 16 re-checked counted members remain separable (k_kept; v222 kept 5/6, v224 8/8,
                           v226 2/2).                                                                                    prior 65%
    pred_c_row4_kept       fam-arm own-C UB975 <= 0.01 on at least 11 of the 22 evaluated members (k_d; v226 2/6, v224 8/11).  prior 45%
    pred_d_instrument      every evaluated member's own-arm extraction is within 0.03 of its parent battery's cdas extraction_held
                           (same units, seed, split and code path: a determinism check, NOT an independent run outcome).  prior 90%
Priors are not moved by unit overlap (v214/v216/v220) nor by a shared readout token (withdrawn at v224).
Smoke: V228_SMOKE=<out.json> (CPU, V228_SMOKE_ROWS=4; all members are prepared as controls, V228_SMOKE_NAMES=degree_synthetic_periphrastic_comparative,comparative_complement_superior
are evaluated so a new member, a re-check and the instrument read are exercised; steps 5).
"""
