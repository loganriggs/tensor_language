"""E27 SEED REPLICATES OF THE TWO RECOMMENDATION ARMS (reviewer-2 finding R4:
every frontier number in this program rests on ONE seed and ONE data order;
the retrain-recommendation rule in BRAINSTORM_STATE demands 2-3 seeds before an
architecture can enter the recommendation).

TWO ARMS, each an exact replicate of a stored arm with the INIT SEED changed
and NOTHING else:
  E27a  frontier arm -- the bandwidth-reinvestment architecture at the
        readability dial (in-loss group-lasso 1e-4): qk_e15_reinvest_run.
        make_e15c(s=15) verbatim, trained through the qk_e19_dial_run trainer
        expression. Seed-0 twin: qk_e19_a (fresh held CE 4.9742, plain
        Spearman 0.7911, covariance-composed 0.8259).
  E27b  readable-recipe arm -- per-slot RMSNorm + Muon + in-loss group-lasso
        3e-5: qk_e7_evenout_run.make_e7m1 verbatim through the
        qk_e9_compose_run.muon_lasso_trainer expression. Seed-0 twin:
        qk_e9_a (fresh held CE 5.0547, plain Spearman 0.7711,
        covariance-composed 0.8575).

WHAT VARIES, EXACTLY ONE THING. Q.SEED (0 -> 1) is consumed ONLY by the model
factories (`torch.manual_seed(Q.SEED)` immediately before construction). The
DATA ORDER is generated by Q.epoch_order(epoch) from the SEPARATE, UNCHANGED
Q.DATA_SEED = 1234, so both replicates see the identical 132,000-row single-
epoch stream in the identical order as their seed-0 twins. This is deliberate:
holding data order fixed makes the measured delta a pure INIT-SENSITIVITY
number, not a joint init+order number. A data-order replicate is a separate
experiment (the standing logging list asks for one) and is NOT what this run
measures -- do not read these deltas as full run-to-run spread.

POSITIVE CONTROLS, BEFORE TRAINING:
  1. CONFIG EQUALITY: the training configuration this runner is about to use
     (lr, group_coeff, width, batch, steps, epochs, corpus, held_fresh,
     adamw lr) must equal the stored parent JSON record field for field. Any
     difference other than the seed aborts the run.
  2. SEED-0 REPRODUCTION: 3 steps through THIS runner's exact training call at
     Q.SEED = 0 must reproduce the stored parent's step-0 training CE exactly
     (the parents log round(ce, 4) at step 0). Proves the replication path is
     the parent's path, so any later difference is attributable to the seed.
  3. SEED ACTUALLY CHANGED: the same 3 steps at Q.SEED = 1 must give a
     DIFFERENT step-0 CE (guards the silent no-op where the factory ignores
     the seed).
  4. AFTER TRAINING: the saved checkpoint config dict must equal the parent
     checkpoint's config dict on every key except SEED (parent 0, replicate 1).

MEASURES (full standard set, per arm): fresh single-epoch training curve every
200 steps + held-100 curve; final fresh held CE; per-sequence heldloss.npy;
old-cooc held record; paired deltas vs the seed-0 twin AND vs the E0a/E0b
controls with sequence-clustered SEs; the generalized variable-slot-dim light
probe (qk_e18 gate-1 validated: reproduces weight_support exactly at uniform
11) giving PLAIN wiring Spearman, and the covariance-composed re-scoring
(qk_e18 gate-2 validated) giving the standard reported metric; wiring-
trajectory npz every 200 steps (harness standing upgrade).

REGISTERED PREDICTIONS (merged before training):
  CE seed spread <= 0.02 nats on both arms.
  Spearman seed spread UNKNOWN -- measuring it IS the point of this run. If
  either metric's spread exceeds 0.08 (the R1 sampling SE, i.e. the size of a
  "tie" on this metric), the frontier's readability axis is seed-dominated and
  every readability comparison in the program needs 3+ seeds; the JSON states
  that consequence explicitly.

Idempotent on qk_e27.json keys and checkpoints; smoke-gated via QK_SMOKE=1."""
