def set_seed(s):
    """Q.SEED is read ONLY by the model factories; the data order comes from
    the untouched Q.DATA_SEED. Setting it globally also stamps the correct
    seed into the checkpoint config dict written by E.train_muon."""
    Q.SEED = s


